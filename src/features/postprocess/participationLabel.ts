/**
 * 「自动后处理」开关的文案。
 *
 * 为什么单独成一个模块：它是**纯文案逻辑**，独立后测试不需要拉起整个参数面板
 * （那边拖着 store、composite、项目树一堆依赖）。
 *
 * 语义（2026-09-23 简化）：只剩**一层** —— 方向级开关（`PostprocessNodeOverride.enabled`，
 * 可被上级继承，默认开）。原先还有第二层「启用范围」（项目树「后处理」列的白名单），
 * 那层已撤掉：用户的诉求是「这些图本来都要后处理，区别只是自动跑还是手动跑」，
 * 而白名单让没被勾上的方向每批都产生一条跳过记录。
 * 所以「未生效」这一档不再存在 —— 开关开着就是会产出。
 *
 * 文案只留最短的必要信息（2026-09-20 反馈「太长的说明又说不明白」）。
 */
export function formatParticipationLabel(enabled: boolean): string {
  return enabled ? '已开启' : '已关闭'
}
